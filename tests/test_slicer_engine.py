def test_filament_properties():
    """Verify density and default extrusion temperatures across filament types."""
    assert FilamentType.PLA.density_g_cm3 == 1.24
    assert FilamentType.PETG.density_g_cm3 == 1.27
    assert FilamentType.ABS.density_g_cm3 == 1.04
    assert FilamentType.RESIN.density_g_cm3 == 1.15

    assert FilamentType.PLA.default_bed_temp == 60
    assert FilamentType.PETG.default_bed_temp == 75
    assert FilamentType.ABS.default_bed_temp == 100

    assert FilamentType.PLA.default_nozzle_temp == 205
    assert FilamentType.PETG.default_nozzle_temp == 235


def test_overhang_analysis():
    """Verify detection of overhang angles and support recommendations."""
    gen = CoinGenerator(radius=20.0, thickness=3.0, serrations=30, resolution=32)
    mesh = gen.generate()

    overhang = analyze_mesh_overhangs(mesh, threshold_degrees=45.0)
    assert isinstance(overhang, OverhangAnalysis)
    assert overhang.total_faces == mesh.triangle_count
    assert overhang.overhang_area_mm2 >= 0.0
    assert 0.0 <= overhang.overhang_percentage <= 100.0
    assert len(overhang.recommendations) > 0


def test_mesh_slicing_layer_count():
    """Verify horizontal layer plane intersection calculations."""
    gen = CoinGenerator(radius=15.0, thickness=2.0, serrations=20, resolution=24)
    mesh = gen.generate()

    cfg = SlicingConfig(layer_height=0.20, first_layer_height=0.25)
    result = slice_mesh(mesh, config=cfg)

    assert isinstance(result, SliceResult)
    assert result.total_layers > 5
    assert len(result.layers) == result.total_layers
    assert result.total_print_time_sec > 0.0
    assert result.total_filament_mm > 0.0
    assert result.total_filament_grams > 0.0

    # Ensure strictly increasing Z heights
    zs = [l.z_height for l in result.layers]
    assert all(zs[i] < zs[i + 1] for i in range(len(zs) - 1))

    # Check serialization
    d = result.to_dict()
    assert "total_layers" in d
    assert "total_filament_grams" in d
    assert "overhang" in d


def test_infill_patterns():
    """Verify rectilinear, grid, concentric, and triangles infill generation."""
    gen = CoinGenerator(radius=15.0, thickness=2.0, resolution=24)
    mesh = gen.generate()

    for pat in [InfillPattern.RECTILINEAR, InfillPattern.GRID, InfillPattern.CONCENTRIC, InfillPattern.TRIANGLES]:
        cfg = SlicingConfig(
            layer_height=0.25,
            infill_density=0.20,
            infill_pattern=pat,
        )
        res = slice_mesh(mesh, config=cfg)
        # Check that middle layers have infill segments
        mid_layer = res.layers[len(res.layers) // 2]
        assert len(mid_layer.infill_segments) > 0, f"Pattern {pat} generated no infill segments"


def test_gcode_synthesis_structure():
    """Verify generated G-code text format adheres to Marlin/RepRap conventions."""
    gen = CoinGenerator(radius=12.0, thickness=2.0, resolution=16)
    mesh = gen.generate()
    cfg = SlicingConfig(layer_height=0.30, filament_type=FilamentType.PLA)
    result = slice_mesh(mesh, config=cfg)
    gcode = result.to_gcode()

    assert "; Generated by Badge3D Coin Slicer" in gcode
    assert "G28 ; home all axes" in gcode
    assert f"M104 S{cfg.nozzle_temp}" in gcode
    assert f"M140 S{cfg.bed_temp}" in gcode
    assert "; --- LAYER 0" in gcode
    assert "M84 ; disable stepper motors" in gcode


