def test_mcp_coin_slice_gcode_tool():
    """Verify MCP tool call for coin_slice_gcode."""
    server = MCPServer()
    req = {
        "jsonrpc": "2.0",
        "id": 42,
        "method": "tools/call",
        "params": {
            "name": "coin_slice_gcode",
            "arguments": {
                "radius": 15.0,
                "thickness": 2.0,
                "layer_height": 0.30,
                "format": "json",
            },
        },
    }
    resp = server.handle_request(req)
    assert resp is not None
    assert "result" in resp
    assert not resp["result"].get("isError")

    text = resp["result"]["content"][0]["text"]
    data = json.loads(text)
    assert "total_layers" in data
    assert data["total_layers"] > 0

    # Summary markdown call
    req_summary = {
        "jsonrpc": "2.0",
        "id": 43,
        "method": "tools/call",
        "params": {
            "name": "coin_slice_gcode",
            "arguments": {
                "radius": 15.0,
                "thickness": 2.0,
                "format": "summary",
            },
        },
    }
    resp_sum = server.handle_request(req_summary)
    assert "G-Code Telemetry" in resp_sum["result"]["content"][0]["text"]


def test_ui_api_slice_gcode_endpoints():
    """Verify GET and POST /api/slice-gcode on ephemeral server."""
    server = create_ui_server(host="127.0.0.1", port=0)
    port = server.server_address[1]
    base_url = f"http://127.0.0.1:{port}"

    th = threading.Thread(target=server.serve_forever, daemon=True)
    th.start()
    time.sleep(0.05)

    try:
        # 1. GET /api/slice-gcode
        get_url = f"{base_url}/api/slice-gcode?radius=15.0&thickness=2.0&layer_height=0.30"
        with urllib.request.urlopen(get_url) as resp:
            assert resp.status == 200
            data = json.loads(resp.read().decode("utf-8"))
            assert "total_layers" in data

        # 2. POST /api/slice-gcode (JSON summary)
        post_url = f"{base_url}/api/slice-gcode"
        body = json.dumps({"radius": 15.0, "thickness": 2.0, "layer_height": 0.30}).encode("utf-8")
        req = urllib.request.Request(post_url, data=body, headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req) as resp:
            assert resp.status == 200
            data = json.loads(resp.read().decode("utf-8"))
            assert "total_layers" in data

        # 3. POST /api/slice-gcode (G-code file download)
        body_gcode = json.dumps({"radius": 15.0, "thickness": 2.0, "layer_height": 0.30, "format": "gcode"}).encode("utf-8")
        req_gcode = urllib.request.Request(post_url, data=body_gcode, headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req_gcode) as resp:
            assert resp.status == 200
            gcode_content = resp.read().decode("utf-8")
            assert "Generated by Badge3D Coin Slicer" in gcode_content
    finally:
        server.shutdown()
        server.server_close()
        th.join(timeout=1.0)


